void showBootLogo(Adafruit_SSD1306 &display) {
  display.clearDisplay();

  // Centrar el bitmap 64x64 en la pantalla (asumiendo OLED 128x64)
  int16_t x = (SCREEN_WIDTH - LOGO_WIDTH) / 2;
  int16_t y = (SCREEN_HEIGHT - LOGO_HEIGHT) / 2;

  display.drawBitmap(x, y, logo_gear, LOGO_WIDTH, LOGO_HEIGHT, SSD1306_WHITE);
  display.display();

  delay(1500); // única excepción válida a "no delay": splash antes del loop()
}

