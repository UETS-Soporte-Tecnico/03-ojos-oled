// ============================================================================
// MOSTRAR LOGO
// ============================================================================

inline void drawSkullLogo(Adafruit_SSD1306 &display) {

  display.clearDisplay();

  // ----------------------------------------------------------
  // Tamaño del bitmap
  // ----------------------------------------------------------

  const int logoWidth  = 40;
  const int logoHeight = 51;

  // ----------------------------------------------------------
  // Centrar automáticamente en OLED 128x64
  // ----------------------------------------------------------

  int x = (SCREEN_WIDTH - logoWidth) / 2;
  int y = (SCREEN_HEIGHT - logoHeight) / 2;

  // ----------------------------------------------------------
  // Dibujar calavera
  // ----------------------------------------------------------

  display.drawBitmap(
    x,
    y,
    epd_bitmap_Calavera,
    logoWidth,
    logoHeight,
    SSD1306_WHITE
  );

  display.display();
}


// ============================================================================
// MOSTRAR LOGO DURANTE EL ARRANQUE
// ============================================================================

inline void showLogo(Adafruit_SSD1306 &display) {

  Serial.println(
    F("[LOGO] Dibujando calavera...")
  );

  // Limpiar pantalla
  display.clearDisplay();
  display.display();

  delay(200);

  // Mostrar logo
  drawSkullLogo(display);

  Serial.println(
    F("[LOGO] Calavera mostrada")
  );

  // Mantener logo visible
  delay(3000);

  // Limpiar antes del POST
  display.clearDisplay();
  display.display();

  delay(200);
}

